export const GENRE_BY_ID = Object.fromEntries(GENRES.map((g) => [g.id, g]));

/** Все записи, привязанные к конкретному району. */
export function entriesForDistrict(districtId) {
  return ENTRIES.filter((e) => e.districts?.includes(districtId));
}

/** Районы, у которых есть хотя бы одна запись. */
export function districtsWithEntries() {
  const set = new Set();
  ENTRIES.forEach((e) => e.districts?.forEach((d) => set.add(d)));
  return set;
}

/** Сюжеты, бытующие по всей республике (не привязаны к точке). */
export const AREA_WIDE = ENTRIES.filter((e) => e.areaWide);
